import esbuild from "esbuild";
import process from "process";
import { copyFileSync, mkdirSync, accessSync } from "fs";
import { dirname } from "path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

// 构建后自动部署到 Obsidian 库的插件目录（ADR-0008 开发流）。
// 默认路径写死在本机；换库时用环境变量覆盖：PLANFLOW_PLUGIN_DIR=<插件目录> npm run build
const PLUGIN_DIR =
  process.env.PLANFLOW_PLUGIN_DIR ??
  "N:/仓库/仓库-新/-0.笔记汇总库/.obsidian/plugins/planflow";

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
});

if (prod) {
  await context.rebuild();
  // 部署：三件套全量覆盖（main.js / manifest.json / styles.css 与仓库保持一致）
  try {
    mkdirSync(PLUGIN_DIR, { recursive: true });
    for (const f of ["main.js", "manifest.json", "styles.css"]) {
      copyFileSync(f, `${PLUGIN_DIR}/${f}`);
    }
    console.log(`deploy: main.js/manifest.json/styles.css -> ${PLUGIN_DIR}`);
  } catch (e) {
    console.warn(`deploy failed (build OK): ${e?.message ?? e}`);
  }
  process.exit(0);
} else {
  await context.watch();
}
